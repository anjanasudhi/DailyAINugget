#!/usr/bin/env python3
"""
Daily FDE Learning Coach Bot
----------------------------
A 15-20 minute daily learning session for a senior manager/FDE-lead
maintaining hands-on AI/ML + engineering depth. Each day has a deep-dive
pillar based on day of week (Mon=AI/ML, Tue=SWE, Wed=news roundup,
Thu=FDE case study, Fri=Martech, Sat=eng leadership, Sun=weekly recap/quiz),
wrapped in the same lightweight daily template every day. Generated by
Claude with web search, then sent by email (Resend API) and Telegram
(Telegram Bot API).

Designed to run on a schedule (cron / GitHub Actions) alongside your
existing WhatsApp goal-notifier script.

SETUP
-----
1. pip install anthropic python-dotenv
2. Email (Resend): create a free account at https://resend.com and copy
   an API key from the dashboard (starts with "re_").
3. Telegram: message @BotFather on Telegram, send "/newbot", follow the
   prompts, and copy the bot token it gives you. Then send your new bot
   any message (e.g. "hi") so it can see your chat, and visit
   https://api.telegram.org/bot<YOUR_TOKEN>/getUpdates in a browser to
   find your numeric chat id under "message" -> "chat" -> "id".
4. Create a .env file (same folder) with:
       ANTHROPIC_API_KEY=sk-ant-...
       RESEND_API_KEY=re_...
       EMAIL_TO=you@example.com
       EMAIL_FROM=onboarding@resend.dev              # optional; see note below
       TELEGRAM_BOT_TOKEN=123456789:AA...
       TELEGRAM_CHAT_ID=123456789
   Note: the shared "onboarding@resend.dev" sender only delivers to the
   email address you signed up to Resend with. To send to any address,
   verify your own domain in the Resend dashboard and set EMAIL_FROM to
   an address on it (e.g. bot@yourdomain.com).
5. Test: python daily_ai_nugget.py --dry-run   (prints message, doesn't send)
6. Schedule it (see .github/workflows/daily-nugget.yml for the GitHub
   Actions version, which runs daily at 9:30 AM IST).

CUSTOMIZING TOPICS
------------------
Edit TOPIC_BANKS to change what each pillar covers. Each pillar has its
own rotating cursor persisted in coach_state.json, so subtopics cycle
through without repeating. PILLAR_BY_WEEKDAY controls which pillar is the
deep-dive for which day (index 0 = Monday ... 6 = Sunday, matching
datetime.weekday()).

NOTE ON INTERACTIVITY
----------------------
The source instructions this bot follows (a conversational "coach" prompt)
assume a live chat where you can reply "quiz me", "more depth", etc., and
where the coach waits to see if you attempted yesterday's interview
question before revealing the answer. This bot is a one-way scheduled
send with no reply-parsing, so those interactive bits are adapted:
the model answer to each day's interview question is always revealed at
the start of the *next* day's message (regardless of whether you actually
attempted it), and steering commands aren't wired up.
"""

