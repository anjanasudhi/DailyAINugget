def load_state() -> dict:
    if STATE_FILE.exists():
        return json.loads(STATE_FILE.read_text())
    return {"cursors": {}, "pending_interview": None, "history": []}


def save_state(state: dict) -> None:
    STATE_FILE.write_text(json.dumps(state, indent=2))


def _next_from_list(state: dict, cursor_key: str, items: list) -> str:
    """Rotating pick from `items`, persisting the cursor under `cursor_key`."""
    idx = state["cursors"].get(cursor_key, 0) % len(items)
    state["cursors"][cursor_key] = (idx + 1) % len(items)
    return items[idx]


def build_plan(state: dict, run_date: datetime, pillar_override: str = None) -> dict:
    """Decide today's pillar/topic/interview category and gather recall context.
    Mutates `state`'s cursors but does not save it."""
    weekday = run_date.weekday()
    pillar = pillar_override or PILLAR_BY_WEEKDAY[weekday]
    next_pillar = PILLAR_BY_WEEKDAY[(weekday + 1) % 7]

    plan = {
        "date": run_date.strftime("%Y-%m-%d"),
        "day_name": run_date.strftime("%A"),
        "pillar": pillar,
        "pillar_label": PILLAR_LABELS[pillar],
        "next_pillar_label": PILLAR_LABELS[next_pillar],
        "foundations_mode": run_date.date() < FOUNDATIONS_MODE_UNTIL,
        "topic": None,
        "fde_snippet_topic": None,
        "interview_category": _next_from_list(state, "interview_category", INTERVIEW_CATEGORIES),
        "pending_interview": state.get("pending_interview"),
        "recent_history": state.get("history", [])[-6:],
    }

    if pillar in TOPIC_BANKS:
        plan["topic"] = _next_from_list(state, pillar, TOPIC_BANKS[pillar])

    # A short FDE case snippet runs every day except Thursday, where the
    # deep-dive slot itself already is the FDE case study.
    if pillar != "fde_case":
        plan["fde_snippet_topic"] = _next_from_list(state, "fde_snippet", TOPIC_BANKS["fde_case"])

    return plan


def _build_prompt(plan: dict) -> str:
    foundations = plan["foundations_mode"]

    if plan["pending_interview"]:
        answer_style = (
            "Write the model answer in plain, foundational language — define any technical "
            "term the first time you use it, don't assume unexplained jargon."
            if foundations else
            "Keep it concise and technical, staff-engineer level."
        )
        pending_block = f"""
0. YESTERDAY'S ANSWER (open with this, before anything else): Yesterday's interview
   question was, in category "{plan['pending_interview']['category']}":
   "{plan['pending_interview']['question']}"
   Assume I likely didn't get to attempt it. Give a concise (4-6 sentence) model answer
   to THIS EXACT question under a clear label (e.g. "↩️ Yesterday's Answer"), then move
   straight on to today's content. {answer_style}"""
    else:
        pending_block = ""

    if plan["recent_history"]:
        history_lines = "\n".join(
            f"- {h['date']} ({h['day_name']}, {h['pillar_label']}): {h['concept_summary']}"
            for h in plan["recent_history"]
        )
        history_context = f"Material covered earlier this week (for the recall check, and on Sundays the recap):\n{history_lines}"
        recall_instruction = """RECALL CHECK: Write 1-2 quick questions testing something from the material
   listed above (NOT today's new content) — spaced repetition, don't skip this even on
   light days. Just ask them; don't answer them."""
    else:
        history_context = "No prior material recorded yet (this is the first session)."
        recall_instruction = "RECALL CHECK: Skip it — say in one short line that recall material is still building up this week."

    plain_language_note = (
        " Write in plain, jargon-light language — define any technical term the first time "
        "you use it, as if for someone technical but new to this specific topic."
        if foundations else ""
    )

    if plan["pillar"] == "news_roundup":
        concept_block = f"""CONCEPT SLOT — DEEP NEWS ROUNDUP: Today's pillar is the news roundup. Search the web
   for 3-4 genuinely recent (last 3-5 days), dated AI/engineering developments relevant
   to a senior AI/engineering leader. For each: a 1-2 sentence summary plus why it
   matters for someone doing AI/eng leadership or FDE work.{plain_language_note} No
   learn-more link needed for this slot."""
    elif plan["pillar"] == "review_quiz":
        concept_block = f"""CONCEPT SLOT — WEEKLY RECAP & QUIZ: No new teaching today. Using the material listed
   above under "covered earlier this week", write one line per concept recapping what
   was covered Monday-Saturday, then turn 2-3 of them into quick recall questions
   (don't answer them).{plain_language_note} No learn-more link needed for this slot."""
    elif plan["pillar"] == "fde_case":
        concept_block = f"""CONCEPT SLOT — DEEP FDE CASE DIVE: Today's deep dive is the FDE case pillar. Write an
   applied scenario around "{plan['topic']}" — set the scene (2-3 sentences), the
   ambiguity or tension in it, then walk through a framework for reasoning through it
   and a concrete example resolution. This is the deep-dive version, so a full page is
   fine here.{plain_language_note} No learn-more link needed for this slot."""
    elif foundations:
        concept_block = f"""CONCEPT OF THE DAY: The topic is "{plan['topic']}". Assume I'm technical and
   experienced generally, but NEW to this specific topic — I'm deliberately spending the
   next few months building 101-level foundations before going deep, so don't skip basics
   here even though you would for other senior-level topics. Structure it in two clearly
   labeled parts:
   PART 1 — THE BASICS: If this topic is really a comparison of multiple building-block
   ideas (e.g. "REST vs GraphQL vs gRPC" or "fine-tuning vs prompting vs RAG"), first
   explain EACH one on its own in plain language with a simple analogy — what it is and
   what problem it solves — before any comparison. If it's a single concept, just explain
   what it is, why it exists, and the simplest possible mental model for it.
   PART 2 — HOW THEY COMPARE / WHY IT MATTERS: Only after part 1 is done, get into the
   tradeoffs, when to use which, a real-world failure mode, and one line on how this shows
   up in an FDE/leadership context. Keep this part shorter than part 1.
   Define any technical term the first time you use it — don't assume unexplained jargon.
   Then give 1-2 "watch/learn more" recommendations: prioritize a genuinely 101/beginner
   level intro resource (one per building-block concept if there are several, e.g. a
   "what is REST" video and a "what is GraphQL" video), optionally followed by ONE
   slightly deeper resource if you want to build up further on the same topic. Pick from
   this preferred list where it fits (don't force 3Blue1Brown into everything, and prefer
   videos explicitly aimed at beginners/explainers over deep technical talks):
{PREFERRED_RESOURCES}
   Only give a URL you found via web search and are sure is correct/live. If you're not
   sure of the exact URL, name the channel/video and give a precise search phrase
   instead (e.g. "search YouTube: what is REST API for beginners") rather than guessing a
   link."""
    else:
        concept_block = f"""CONCEPT OF THE DAY: Explain "{plan['topic']}" the way you'd explain it to a strong
   staff engineer — skip 101-level basics, go straight to the mechanism, why it matters,
   and a real tradeoff or production failure mode. Close with one line on how this shows
   up in an FDE/leadership context. Then give ONE "watch/learn more" recommendation —
   whichever fits the topic best from this preferred list (don't force 3Blue1Brown into
   everything):
{PREFERRED_RESOURCES}
   Only give a URL you found via web search and are sure is correct/live. If you're not
   sure of the exact URL, name the channel/video and give a precise search phrase
   instead (e.g. "search YouTube: 3Blue1Brown attention in transformers") rather than
   guessing a link."""

    if plan["fde_snippet_topic"]:
        fde_snippet_block = f"""FDE CASE SNIPPET: Write a short applied scenario (2-4 sentences) around
   "{plan['fde_snippet_topic']}" that I have to reason through — end on an open question,
   don't give the answer, keep it brief.{plain_language_note}"""
    else:
        fde_snippet_block = ""

    interview_block = f"""INTERVIEW QUESTION OF THE DAY — category: {plan['interview_category']}
   Write ONE realistic interview question in this category, pitched at a senior
   candidate. Give ONLY the question — no answer, no hints. I'll attempt it myself; the
   model answer gets revealed at the start of tomorrow's message."""

    sign_off_line = (
        f"one line signing off, noting tomorrow's deep-dive pillar is \"{plan['next_pillar_label']}\" "
        "(use that exact phrase — don't rename or paraphrase it; don't invent interactive commands "
        "like \"reply X\" — this is a one-way message, not a live chat)"
    )

    if foundations:
        calibration = """I'm senior in my actual job (management/stakeholder work), but genuinely NEW to a lot
of the hands-on AI/engineering material this session covers — I'm deliberately spending
the next few months building 101-level foundations before ramping back up to advanced
material. So across EVERY section below (not just the concept of the day): explain things
plainly, define technical terms and acronyms the first time you use them, don't assume
unexplained jargon, and don't rush past the basics to get to the "interesting" tradeoff
part. It's fine for an explanation to spend most of its length on fundamentals."""
    else:
        calibration = """I'm senior, not a beginner. Skip 101-level definitions unless I ask for them. Go
straight to the mechanism, the tradeoff, or the "here's what actually breaks in
production" angle."""

    return f"""You are my daily learning coach. I'm a senior manager leading AI/engineering
teams and working toward an FDE (Forward Deployed Engineer) Lead role. {calibration} This
is maintenance, not cramming: keep the tone like a smart peer doing a daily sync. Optimize
for retention over coverage.

Today is {plan['day_name']}, {plan['date']}. Today's deep-dive pillar is: {plan['pillar_label']}.

{history_context}

Write today's message with these parts, IN THIS ORDER:
{pending_block}
1. QUICK-HIT NEWS: Search the web for 2-3 recent, dated AI/engineering developments
   worth knowing about (skip this if today's pillar is the news roundup — that gets its
   own deeper treatment below instead). Keep each to one line with a date.

2. {concept_block}

3. {fde_snippet_block if fde_snippet_block else "(no separate FDE case snippet today — the deep dive above covers it)"}

4. {interview_block}

5. {recall_instruction}

6. SIGN-OFF: {sign_off_line}.

FORMATTING: This is a plain-text email/Telegram message, not a markdown renderer — any
markdown you write will show up as literal stray characters, not formatting. So: never
use asterisks for bold/italic (*, **), never use # headers, never use backtick code
spans, never use markdown links ([text](url)) — just write the URL bare. Use plain
sentence structure, blank lines between ideas (never more than one blank line in a row),
and a simple "-" for list items where needed. Emoji are fine sparingly for section
headers. Do not add any preamble like "Here's your session" — start directly with the
content. Do not narrate your search process or explain your choices anywhere in the
output.

After ALL of the above, on new lines, append EXACTLY this machine-readable block (it will
be stripped before sending to me, so it must not duplicate content I need to read — just
the two lines below, nothing else in the block):
<<<STATE>>>
INTERVIEW_QUESTION: <verbatim text of the interview question you wrote in part 4, one line>
CONCEPT_SUMMARY: <one line, under 15 words, summarizing today's main content (the concept/news-roundup/case/recap topic)>
<<<END_STATE>>>"""


def _split_state_block(text: str) -> tuple:
    marker = "<<<STATE>>>"
    end_marker = "<<<END_STATE>>>"
    if marker not in text:
        return text.strip(), {}
    body, _, rest = text.partition(marker)
    state_block, _, _ = rest.partition(end_marker)
    meta = {}
    for line in state_block.strip().splitlines():
        if ":" in line:
            key, _, value = line.partition(":")
            meta[key.strip()] = value.strip()
    return body.strip(), meta


def generate_nugget(plan: dict) -> tuple:
    """Call Claude (with web search) to produce today's coaching message.
    Returns (message_text, meta_dict)."""
    client = anthropic.Anthropic()  # reads ANTHROPIC_API_KEY from env

    response = client.messages.create(
        model="claude-sonnet-4-6",
        max_tokens=6000,
        tools=[{"type": "web_search_20250305", "name": "web_search"}],
        messages=[{"role": "user", "content": _build_prompt(plan)}],
    )

    text_parts = [block.text for block in response.content if block.type == "text"]
    raw = "\n".join(text_parts).strip()

    header = f"📅 {plan['day_name']}, {plan['date']} — Today's deep dive: {plan['pillar_label']}"
    body, meta = _split_state_block(raw)
    # Web-search citation markers leave stray blank lines behind when stripped;
    # collapse any run of 2+ blank lines down to exactly one.
    body = re.sub(r"\n\s*\n(\s*\n)+", "\n\n", body)
    return f"{header}\n\n{body}", meta


def send_email(subject: str, message: str) -> None:
    import urllib.request
    import urllib.error

    api_key = os.environ["RESEND_API_KEY"]
    from_address = os.environ.get("EMAIL_FROM", "onboarding@resend.dev")
    to_address = os.environ["EMAIL_TO"]

    payload = json.dumps({
        "from": from_address,
        "to": [to_address],
        "subject": subject,
        "text": message,
    }).encode("utf-8")

    request = urllib.request.Request(
        "https://api.resend.com/emails",
        data=payload,
        headers={
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
            "User-Agent": "Mozilla/5.0 (compatible; daily-ai-nugget/1.0)",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(request) as response:
            result = json.loads(response.read())
    except urllib.error.HTTPError as e:
        raise RuntimeError(f"Resend API error {e.code}: {e.read().decode()}") from e

    print(f"Sent email to {to_address}. Resend id: {result.get('id')}")


TELEGRAM_MAX_LEN = 4000  # Telegram's hard limit is 4096 chars; leave some headroom


def _chunk_message(message: str, max_len: int) -> list:
    """Split into chunks <= max_len, breaking on blank lines/newlines where possible."""
    if len(message) <= max_len:
        return [message]

    chunks = []
    remaining = message
    while len(remaining) > max_len:
        split_at = remaining.rfind("\n\n", 0, max_len)
        if split_at == -1:
            split_at = remaining.rfind("\n", 0, max_len)
        if split_at == -1:
            split_at = max_len
        chunks.append(remaining[:split_at].strip())
        remaining = remaining[split_at:].strip()
    if remaining:
        chunks.append(remaining)
    return chunks


def send_telegram(message: str) -> None:
    import urllib.request
    import urllib.error

    bot_token = os.environ["TELEGRAM_BOT_TOKEN"]
    chat_id = os.environ["TELEGRAM_CHAT_ID"]

    for chunk in _chunk_message(message, TELEGRAM_MAX_LEN):
        payload = json.dumps({
            "chat_id": chat_id,
            "text": chunk,
        }).encode("utf-8")

        request = urllib.request.Request(
            f"https://api.telegram.org/bot{bot_token}/sendMessage",
            data=payload,
            headers={
                "Content-Type": "application/json",
                "User-Agent": "Mozilla/5.0 (compatible; daily-ai-nugget/1.0)",
            },
            method="POST",
        )
        try:
            with urllib.request.urlopen(request) as response:
                result = json.loads(response.read())
        except urllib.error.HTTPError as e:
            raise RuntimeError(f"Telegram API error {e.code}: {e.read().decode()}") from e

        print(f"Sent Telegram message. Message id: {result['result']['message_id']}")


def main():
    parser = argparse.ArgumentParser(description="Daily FDE learning coach sender")
    parser.add_argument("--dry-run", action="store_true", help="Print message, don't send")
    parser.add_argument("--pillar", type=str, choices=list(PILLAR_LABELS),
                         help="Override today's deep-dive pillar (for testing)")
    parser.add_argument("--reset-state", action="store_true",
                         help="Wipe coach_state.json (rotation cursors, pending question, history)")
    args = parser.parse_args()

    if args.reset_state:
        save_state({"cursors": {}, "pending_interview": None, "history": []})
        print("Coach state reset.")

    state = load_state()
    run_date = now_ist()
    plan = build_plan(state, run_date, pillar_override=args.pillar)
    print(f"[{run_date.isoformat(timespec='seconds')}] {plan['day_name']} — pillar: {plan['pillar_label']}"
          + (f" — topic: {plan['topic']}" if plan["topic"] else ""))

    message, meta = generate_nugget(plan)
    print("---- MESSAGE ----")
    print(message)
    print("-----------------")

    if meta.get("INTERVIEW_QUESTION"):
        state["pending_interview"] = {
            "category": plan["interview_category"],
            "question": meta["INTERVIEW_QUESTION"],
        }
    state.setdefault("history", []).append({
        "date": plan["date"],
        "day_name": plan["day_name"],
        "pillar_label": plan["pillar_label"],
        "concept_summary": meta.get("CONCEPT_SUMMARY", plan["topic"] or plan["pillar_label"]),
    })
    state["history"] = state["history"][-8:]
    save_state(state)

    if args.dry_run:
        print("(dry run — not sent, but state was still advanced)")
        return

    subject = f"Daily Coach — {plan['day_name']}: {plan['topic'] or plan['pillar_label']}"
    send_email(subject, message)
    send_telegram(message)


if __name__ == "__main__":
    sys.exit(main())
